const GLYPH_WIDTH = 3;
const SPACING = 1;

export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_WIDTH + SPACING) - SPACING;
}

/** Paints upper-case text with its top-left corner at (x, y). */
export function paintText(buf: PixelBuffer, text: string, x: number, y: number, color: string) {
  [...text].forEach((ch, i) => {
    const glyph = FONT_3X5[ch];
    if (!glyph) throw new Error(`The sign font has no glyph for "${ch}"`);
    const left = x + i * (GLYPH_WIDTH + SPACING);
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++)
        if (row[gx] === "#") buf.set(left + gx, y + gy, color);
    });
  });
}
